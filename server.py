#!/usr/bin/env python3
"""Local IELTS learning site prototype with SQLite-backed accounts."""
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from http.cookies import SimpleCookie
from pathlib import Path
from urllib.parse import urlparse, unquote
import hashlib, hmac, json, os, secrets, sqlite3, time
import io, zipfile
import xml.etree.ElementTree as ET
from email import policy
from email.parser import BytesParser

try:
    import psycopg
except ImportError:
    psycopg = None

ROOT = Path(__file__).resolve().parent
DB = Path(os.environ.get("DATABASE_PATH", str(ROOT / "learning_site.sqlite3"))).expanduser()
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
SESSIONS = {}  # token -> (user_id, expiry); local prototype, cleared on restart
SESSION_TTL = 60 * 60 * 24 * 14

class HybridRow(dict):
    """Mapping row that also supports the positional indexing used by sqlite3.Row."""
    def __init__(self, columns, values):
        super().__init__(zip(columns, values))
        self._columns = columns
    def __getitem__(self, key):
        if isinstance(key, int):
            key = self._columns[key]
        return super().__getitem__(key)

class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection
    def __enter__(self):
        self.connection.__enter__()
        return self
    def __exit__(self, *args):
        return self.connection.__exit__(*args)
    def execute(self, sql, params=()):
        return self.connection.execute(sql.replace("?", "%s"), params)
    def executemany(self, sql, params):
        return self.connection.executemany(sql.replace("?", "%s"), params)

def connect():
    if DATABASE_URL:
        if psycopg is None:
            raise RuntimeError("DATABASE_URL requires the psycopg package")
        def row_factory(cursor):
            return lambda values: HybridRow([column.name for column in cursor.description], values)
        return PostgresConnection(psycopg.connect(DATABASE_URL, row_factory=row_factory))
    DB.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    return conn

def init_db():
    with connect() as db:
        if DATABASE_URL:
            db.execute("""CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                display_name TEXT NOT NULL, password_hash TEXT NOT NULL,
                salt TEXT NOT NULL, created_at BIGINT NOT NULL,
                role TEXT NOT NULL DEFAULT 'member')""")
            db.execute("""CREATE TABLE IF NOT EXISTS progress (
                user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                speaking_done INTEGER NOT NULL DEFAULT 0,
                writing_done INTEGER NOT NULL DEFAULT 0,
                saved_topics TEXT NOT NULL DEFAULT '[]')""")
            db.execute("""CREATE TABLE IF NOT EXISTS questions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                part INTEGER NOT NULL CHECK(part BETWEEN 1 AND 3),
                topic TEXT NOT NULL DEFAULT '', question TEXT NOT NULL,
                created_at BIGINT NOT NULL, created_by BIGINT REFERENCES users(id),
                translation TEXT NOT NULL DEFAULT '', answer_structure TEXT NOT NULL DEFAULT '')""")
        else:
            db.execute("""CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY, email TEXT NOT NULL UNIQUE COLLATE NOCASE,
                display_name TEXT NOT NULL, password_hash TEXT NOT NULL,
                salt TEXT NOT NULL, created_at INTEGER NOT NULL,
                role TEXT NOT NULL DEFAULT 'member')""")
            columns = {row[1] for row in db.execute("PRAGMA table_info(users)")}
            if "role" not in columns:
                db.execute("ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'member'")
            db.execute("""CREATE TABLE IF NOT EXISTS progress (
                user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                speaking_done INTEGER NOT NULL DEFAULT 0,
                writing_done INTEGER NOT NULL DEFAULT 0,
                saved_topics TEXT NOT NULL DEFAULT '[]')""")
            db.execute("""CREATE TABLE IF NOT EXISTS questions (
                id INTEGER PRIMARY KEY, part INTEGER NOT NULL CHECK(part BETWEEN 1 AND 3),
                topic TEXT NOT NULL DEFAULT '', question TEXT NOT NULL,
                created_at INTEGER NOT NULL, created_by INTEGER REFERENCES users(id))""")
            question_columns = {row[1] for row in db.execute("PRAGMA table_info(questions)")}
            if "translation" not in question_columns:
                db.execute("ALTER TABLE questions ADD COLUMN translation TEXT NOT NULL DEFAULT ''")
            if "answer_structure" not in question_columns:
                db.execute("ALTER TABLE questions ADD COLUMN answer_structure TEXT NOT NULL DEFAULT ''")
        admin_email = os.environ.get("ADMIN_EMAIL", "").strip().lower()
        if admin_email:
            db.execute("UPDATE users SET role=CASE WHEN lower(email)=? THEN 'admin' ELSE 'member' END", (admin_email,))
        elif os.environ.get("ENVIRONMENT", "").lower() != "production" and not db.execute("SELECT 1 FROM users WHERE role='admin' LIMIT 1").fetchone():
            first = db.execute("SELECT id FROM users ORDER BY id LIMIT 1").fetchone()
            if first:
                db.execute("UPDATE users SET role='admin' WHERE id=?", (first[0],))

def password_digest(password, salt):
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), 240_000).hex()

class Handler(BaseHTTPRequestHandler):
    server_version = "SpeakWriteLocal/1.0"
    def log_message(self, *_):
        pass
    def send_json(self, status, data, cookie=None, clear=False):
        body = json.dumps(data, ensure_ascii=False).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        if cookie:
            secure = "; Secure" if os.environ.get("COOKIE_SECURE", "").lower() in ("1", "true", "yes") else ""
            self.send_header("Set-Cookie", f"session={cookie}; HttpOnly; SameSite=Lax; Path=/; Max-Age={SESSION_TTL}{secure}")
        if clear:
            self.send_header("Set-Cookie", "session=; HttpOnly; SameSite=Lax; Path=/; Max-Age=0")
        self.end_headers(); self.wfile.write(body)
    def read_json(self):
        try:
            size = int(self.headers.get("Content-Length", "0"))
            if size > 1_000_000: return None
            return json.loads(self.rfile.read(size) or b"{}")
        except (ValueError, json.JSONDecodeError): return None
    def current_user(self):
        jar = SimpleCookie(self.headers.get("Cookie", ""))
        token = jar.get("session").value if jar.get("session") else ""
        entry = SESSIONS.get(token)
        if not entry: return None
        user_id, expiry = entry
        if expiry < time.time(): SESSIONS.pop(token, None); return None
        with connect() as db:
            row = db.execute("SELECT id,email,display_name,role FROM users WHERE id=?", (user_id,)).fetchone()
        return (dict(row), token) if row else None
    def do_GET(self):
        path = urlparse(self.path).path
        if path == "/api/questions":
            auth = self.current_user()
            if not auth: return self.send_json(401, {"error":"请先登录"})
            if auth[0]["role"] != "admin":
                return self.send_json(403, {"error":"题库访问权限尚未开通，请联系客服开通。"})
            try: part = int(urlparse(self.path).query.split("part=")[1].split("&")[0])
            except (IndexError, ValueError): return self.send_json(400, {"error":"请选择 Part 1、2 或 3"})
            if part not in (1, 2, 3): return self.send_json(400, {"error":"请选择 Part 1、2 或 3"})
            with connect() as db:
                total = db.execute("SELECT COUNT(*) FROM questions WHERE part=?", (part,)).fetchone()[0]
                rows = db.execute("SELECT id,part,topic,question,translation,answer_structure FROM questions WHERE part=? ORDER BY id DESC", (part,)).fetchall()
            return self.send_json(200, {"questions":[dict(row) for row in rows], "preview":False, "total":total})
        if path == "/api/me":
            auth = self.current_user()
            if not auth: return self.send_json(401, {"error":"请先登录"})
            user, _ = auth
            with connect() as db:
                p = db.execute("SELECT speaking_done,writing_done,saved_topics FROM progress WHERE user_id=?", (user["id"],)).fetchone()
            user.update({"speaking_done":p[0],"writing_done":p[1],"saved_topics":json.loads(p[2])})
            return self.send_json(200, {"user":user})
        if path == "/api/health": return self.send_json(200, {"ok":True})
        if path == "/": path = "/index.html"
        if path.startswith("/api/"): return self.send_json(404, {"error":"接口不存在"})
        target = (ROOT / unquote(path.lstrip("/"))).resolve()
        if ROOT not in target.parents or not target.is_file():
            self.send_error(404); return
        types={".html":"text/html; charset=utf-8", ".css":"text/css; charset=utf-8", ".js":"text/javascript; charset=utf-8", ".png":"image/png", ".svg":"image/svg+xml"}
        data=target.read_bytes(); self.send_response(200); self.send_header("Content-Type", types.get(target.suffix,"application/octet-stream")); self.send_header("Content-Length",str(len(data))); self.send_header("X-Content-Type-Options","nosniff"); self.end_headers(); self.wfile.write(data)
    def do_POST(self):
        path=urlparse(self.path).path
        if path == "/api/admin/questions/upload":
            return self.upload_question_document()
        data=self.read_json()
        if data is None: return self.send_json(400,{"error":"请求内容无效"})
        if path == "/api/register":
            email=str(data.get("email"," ")).strip().lower(); name=str(data.get("name"," ")).strip()[:40]; password=str(data.get("password",""))
            if len(email)>254 or "@" not in email or len(password)<8 or len(password)>200 or not name:
                return self.send_json(400,{"error":"请填写有效邮箱、姓名，并设置至少 8 位密码"})
            salt=secrets.token_hex(16); digest=password_digest(password,salt)
            configured_admin = os.environ.get("ADMIN_EMAIL", "").strip().lower()
            role = "admin" if configured_admin and email == configured_admin else "member"
            try:
                with connect() as db:
                    cur=db.execute("INSERT INTO users(email,display_name,password_hash,salt,created_at,role) VALUES(?,?,?,?,?,?) RETURNING id",(email,name,digest,salt,int(time.time()),role))
                    user_id=cur.fetchone()[0]; db.execute("INSERT INTO progress(user_id) VALUES(?)",(user_id,))
            except Exception as exc:
                duplicate = isinstance(exc, sqlite3.IntegrityError) or (psycopg is not None and isinstance(exc, psycopg.errors.UniqueViolation))
                if duplicate: return self.send_json(409,{"error":"这个邮箱已经注册"})
                raise
            token=secrets.token_urlsafe(32); SESSIONS[token]=(user_id,time.time()+SESSION_TTL)
            return self.send_json(201,{"ok":True},cookie=token)
        if path == "/api/login":
            email=str(data.get("email"," ")).strip().lower(); password=str(data.get("password",""))
            with connect() as db: row=db.execute("SELECT id,password_hash,salt FROM users WHERE email=?",(email,)).fetchone()
            if not row or not hmac.compare_digest(password_digest(password,row["salt"]),row["password_hash"]):
                return self.send_json(401,{"error":"邮箱或密码不正确"})
            token=secrets.token_urlsafe(32); SESSIONS[token]=(row["id"],time.time()+SESSION_TTL)
            return self.send_json(200,{"ok":True},cookie=token)
        if path == "/api/logout":
            auth=self.current_user()
            if auth: SESSIONS.pop(auth[1],None)
            return self.send_json(200,{"ok":True},clear=True)
        if path == "/api/progress":
            auth=self.current_user()
            if not auth: return self.send_json(401,{"error":"请先登录"})
            user,_=auth; speaking=max(0,min(100,int(data.get("speaking_done",0)))); writing=max(0,min(100,int(data.get("writing_done",0))))
            saved=data.get("saved_topics",[])
            if not isinstance(saved,list) or len(saved)>100 or any(not isinstance(x,str) or len(x)>120 for x in saved): return self.send_json(400,{"error":"收藏内容格式不正确"})
            with connect() as db: db.execute("UPDATE progress SET speaking_done=?,writing_done=?,saved_topics=? WHERE user_id=?",(speaking,writing,json.dumps(list(dict.fromkeys(saved)),ensure_ascii=False),user["id"]))
            return self.send_json(200,{"ok":True})
        if path == "/api/admin/questions":
            auth=self.current_user()
            if not auth: return self.send_json(401,{"error":"请先登录"})
            user,_=auth
            if user["role"] != "admin": return self.send_json(403,{"error":"只有管理员可以导入题目"})
            items=data.get("questions")
            if not isinstance(items,list) or not items or len(items)>1000:
                return self.send_json(400,{"error":"请提供 1–1000 条题目"})
            clean=[]
            for item in items:
                try:
                    part=int(item.get("part")); topic=str(item.get("topic","")).strip()[:100]; question=str(item.get("question","")).strip()[:1000]
                    translation=str(item.get("translation","")).strip()[:2000]; answer_structure=str(item.get("answer_structure","")).strip()[:1000]
                except (AttributeError,TypeError,ValueError): return self.send_json(400,{"error":"题目格式无效"})
                if part not in (1,2,3) or not question: return self.send_json(400,{"error":"每条题目都需选择 Part 并填写题目内容"})
                clean.append((part,topic,question,translation,answer_structure,int(time.time()),user["id"]))
            with connect() as db:
                db.executemany("INSERT INTO questions(part,topic,question,translation,answer_structure,created_at,created_by) VALUES(?,?,?,?,?,?,?)",clean)
            return self.send_json(201,{"ok":True,"count":len(clean)})
        if path == "/api/admin/questions/edit":
            auth=self.current_user()
            if not auth: return self.send_json(401,{"error":"请先登录"})
            user,_=auth
            if user["role"] != "admin": return self.send_json(403,{"error":"只有管理员可以编辑题目"})
            try:
                question_id=int(data.get("id")); part=int(data.get("part"))
                topic=str(data.get("topic","")).strip()[:100]
                question=str(data.get("question","")).strip()[:1000]
                translation=str(data.get("translation","")).strip()[:2000]
                answer_structure=str(data.get("answer_structure","")).strip()[:1000]
            except (TypeError,ValueError): return self.send_json(400,{"error":"题目格式无效"})
            if question_id < 1 or part not in (1,2,3) or not question:
                return self.send_json(400,{"error":"请填写有效 Part 和题目内容"})
            with connect() as db:
                cur=db.execute("UPDATE questions SET part=?,topic=?,question=?,translation=?,answer_structure=? WHERE id=?",(part,topic,question,translation,answer_structure,question_id))
            if not cur.rowcount: return self.send_json(404,{"error":"题目不存在或已删除"})
            return self.send_json(200,{"ok":True})
        return self.send_json(404,{"error":"接口不存在"})

    def upload_question_document(self):
        auth=self.current_user()
        if not auth: return self.send_json(401,{"error":"请先登录"})
        user,_=auth
        if user["role"] != "admin": return self.send_json(403,{"error":"只有管理员可以上传题目文档"})
        try:
            length=int(self.headers.get("Content-Length","0"))
            if length<=0 or length>6_000_000: return self.send_json(400,{"error":"文档大小需小于 5 MB"})
            content_type=self.headers.get("Content-Type","")
            raw=b"Content-Type: "+content_type.encode()+b"\r\nMIME-Version: 1.0\r\n\r\n"+self.rfile.read(length)
            message=BytesParser(policy=policy.default).parsebytes(raw)
            filepart=next((p for p in message.iter_parts() if p.get_param("name",header="content-disposition")=="file"),None)
            partfield=next((p for p in message.iter_parts() if p.get_param("name",header="content-disposition")=="part"),None)
            topicfield=next((p for p in message.iter_parts() if p.get_param("name",header="content-disposition")=="topic"),None)
            if not filepart: return self.send_json(400,{"error":"请选择要上传的文档"})
            filename=(filepart.get_filename() or "").lower()
            filedata=filepart.get_payload(decode=True) or b""
            selected_part=int(partfield.get_content().strip()) if partfield else 0
            selected_topic=topicfield.get_content().strip()[:100] if topicfield else ""
            if selected_part not in (1,2,3): return self.send_json(400,{"error":"请选择 Part 1、2 或 3"})
            if filename.endswith((".txt",".csv")):
                text=filedata.decode("utf-8-sig")
            elif filename.endswith(".docx"):
                with zipfile.ZipFile(io.BytesIO(filedata)) as doc:
                    root=ET.fromstring(doc.read("word/document.xml"))
                ns="{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
                paragraphs=[]
                for para in root.iter(ns+"p"):
                    pieces=[]
                    for node in para.iter():
                        if node.tag==ns+"t": pieces.append(node.text or "")
                        elif node.tag==ns+"tab": pieces.append("\t")
                    line="".join(pieces).strip()
                    if line: paragraphs.append(line)
                text="\n".join(paragraphs)
            else:
                return self.send_json(400,{"error":"目前支持 .docx、.txt 和 .csv 文档"})
        except (ValueError,UnicodeDecodeError,zipfile.BadZipFile,KeyError,ET.ParseError):
            return self.send_json(400,{"error":"文档无法读取，请检查文件格式和编码"})
        lines=[line.strip() for line in text.splitlines() if line.strip()]
        if not lines or len(lines)>1000: return self.send_json(400,{"error":"文档需包含 1–1000 行题目"})
        clean=[]
        for line in lines:
            if line.lower().startswith("topic,") or line.lower().startswith("主题,"): continue
            if line.lower().startswith("topic\t") or line.startswith("主题\t"): continue
            if "\t" in line: fields=line.split("\t")
            elif filename.endswith(".csv") and "," in line: fields=line.split(",")
            else: fields=[]
            if fields:
                topic=fields[0].strip()[:100]; question=fields[1].strip() if len(fields)>1 else ""
                translation=fields[2].strip() if len(fields)>2 else ""
                answer_structure=fields[3].strip() if len(fields)>3 else ""
            else: topic,question,translation,answer_structure=selected_topic,line,"",""
            question=question.strip()
            if question: clean.append((selected_part,topic.strip()[:100],question[:1000],translation[:2000],answer_structure[:1000],int(time.time()),user["id"]))
        if not clean: return self.send_json(400,{"error":"文档中没有找到可导入的题目"})
        with connect() as db:
            db.executemany("INSERT INTO questions(part,topic,question,translation,answer_structure,created_at,created_by) VALUES(?,?,?,?,?,?,?)",clean)
        return self.send_json(201,{"ok":True,"count":len(clean)})

if __name__ == "__main__":
    init_db()
    host=os.environ.get("HOST","127.0.0.1"); port=int(os.environ.get("PORT","8000"))
    print(f"IELTS learning site running at http://{host}:{port}")
    ThreadingHTTPServer((host,port),Handler).serve_forever()
